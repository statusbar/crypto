"""Emit hpke_vectors.hpp from the CFRG HPKE test-vectors.json (RFC 9180).

The IRTF CFRG publishes the full RFC 9180 vector grid at
https://github.com/cfrg/draft-irtf-cfrg-hpke (test-vectors.json). This keeps
the suites statusbar implements - DHKEM(P-256, HKDF-SHA256) 0x0010 and
DHKEM(X25519, HKDF-SHA256) 0x0020 with HKDF-SHA256 0x0001 and AES-128-GCM
0x0001 / AES-256-GCM 0x0002, all four modes - with the encryptions at the sequence numbers the RFC's Appendix A
itself prints (0, 1, 2, 4, 255, 256) and every export, as hex string
literals for `statusbar/crypto/hpke/hpke_test.cpp`.

Usage:
    uv run crypto/python/crypto/gen_hpke_kats.py test-vectors.json \
        > crypto/statusbar/crypto/hpke/hpke_vectors.hpp
"""

import json
import sys

KEEP_SEQ = (0, 1, 2, 4, 255, 256)
SCALARS = (
    "ikmE",
    "skEm",
    "pkEm",
    "ikmR",
    "skRm",
    "pkRm",
    "ikmS",
    "skSm",
    "pkSm",
    "psk",
    "psk_id",
    "enc",
    "shared_secret",
    "info",
    "key_schedule_context",
    "secret",
    "key",
    "base_nonce",
    "exporter_secret",
)


def main() -> int:
    with open(sys.argv[1], encoding="utf-8") as fh:
        vectors = json.load(fh)
    kept = [
        v
        for v in vectors
        if v["kem_id"] in (0x0010, 0x0020)
        and v["kdf_id"] == 0x0001
        and v["aead_id"] in (1, 2)
    ]
    kept.sort(key=lambda v: (v["kem_id"], v["aead_id"], v["mode"]))
    print("// Copyright 2026 Jeff Koftinoff <jeff.koftinoff@statusbar.com>")
    print("// SPDX-License-Identifier: MIT")
    print("//")
    print("// GENERATED by crypto/python/crypto/gen_hpke_kats.py - do not edit.")
    print(
        "// Source: IRTF CFRG RFC 9180 test-vectors.json (github.com/cfrg/draft-irtf-cfrg-hpke):"
    )
    print("// DHKEM(P-256, HKDF-SHA256) and DHKEM(X25519, HKDF-SHA256) / HKDF-SHA256 /")
    print("// AES-128-GCM and AES-256-GCM, modes 0-3,")
    print(
        "// encryptions at seq 0, 1, 2, 4, 255, 256 and every export. Hex strings, as published."
    )
    print()
    print("#pragma once")
    print()
    print("#include <array>")
    print("#include <cstdint>")
    print("#include <string_view>")
    print()
    print("// clang-format off")
    print("namespace statusbar::crypto::rfc9180 {")
    print()
    print(
        "struct Encryption { uint64_t seq; std::string_view aad; std::string_view nonce; std::string_view pt; std::string_view ct; };"
    )
    print(
        "struct Export { std::string_view exporter_context; size_t length; std::string_view exported_value; };"
    )
    print("struct Vector")
    print("{")
    print("    uint8_t mode; uint16_t kem_id; uint16_t kdf_id; uint16_t aead_id;")
    for name in SCALARS:
        print(f"    std::string_view {name};")
    print("    std::array<Encryption, %d> encryptions;" % len(KEEP_SEQ))
    print("    std::array<Export, 3> exports;")
    print("};")
    print()
    print(f"inline constexpr std::array<Vector, {len(kept)}> vectors{{{{")
    for v in kept:
        encs = [e for i, e in enumerate(v["encryptions"]) if i in KEEP_SEQ]
        assert len(encs) == len(KEEP_SEQ) and len(v["exports"]) == 3
        print("    {")
        print(
            f"        {v['mode']}, 0x{v['kem_id']:04X}, 0x{v['kdf_id']:04X}, 0x{v['aead_id']:04X},"
        )
        for name in SCALARS:
            print(f'        "{v.get(name, "")}",')
        print("        {{")
        for seq, e in zip(KEEP_SEQ, encs):
            print(
                f'            {{{seq}, "{e["aad"]}", "{e["nonce"]}", "{e["pt"]}", "{e["ct"]}"}},'
            )
        print("        }},")
        print("        {{")
        for x in v["exports"]:
            print(
                f'            {{"{x["exporter_context"]}", {x["L"]}, "{x["exported_value"]}"}},'
            )
        print("        }},")
        print("    },")
    print("}};")
    print()
    print("}  // namespace statusbar::crypto::rfc9180")
    print("// clang-format on")
    return 0


if __name__ == "__main__":
    sys.exit(main())
