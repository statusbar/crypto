"""Emit aes_gcm_wycheproof_vectors.hpp from Wycheproof's aes_gcm_test.json.

Project Wycheproof (https://github.com/C2SP/wycheproof, Apache-2.0) publishes
AES-GCM test vectors with known-tricky cases: counter wrap inside a message,
modified tags, special-case GHASH inputs. This script keeps the groups the
statusbar profile offers (AES-128 and AES-256 keys, 96-bit IV, 128-bit tag)
and writes them as a C++ header of hex string literals for
`statusbar/crypto/aes_gcm/aes128_gcm_test.cpp` and `aes256_gcm_test.cpp`.

Usage:
    uv run crypto/python/crypto/gen_aes_gcm_kats.py testvectors_v1/aes_gcm_test.json \
        > crypto/statusbar/crypto/aes_gcm/aes_gcm_wycheproof_vectors.hpp
"""

import json
import sys


def emit_group(name: str, key_size: int, data: dict) -> None:
    rows = []
    for group in data["testGroups"]:
        if (
            group["keySize"] != key_size
            or group["ivSize"] != 96
            or group["tagSize"] != 128
        ):
            continue
        for t in group["tests"]:
            flags = ",".join(t.get("flags", []))
            comment = t.get("comment", "").replace("\\", "\\\\").replace('"', '\\"')
            valid = "true" if t["result"] == "valid" else "false"
            rows.append(
                f'    {{{t["tcId"]}, "{comment}", "{flags}", "{t["key"]}", "{t["iv"]}", '
                f'"{t["aad"]}", "{t["msg"]}", "{t["ct"]}", "{t["tag"]}", {valid}}},'
            )
    print(f"inline constexpr std::array<AeadVector, {len(rows)}> {name}{{{{")
    print("\n".join(rows))
    print("}};")
    print()


def main() -> int:
    with open(sys.argv[1], encoding="utf-8") as fh:
        data = json.load(fh)
    source = data["testGroups"][0]["source"]
    print("// Copyright 2026 Jeff Koftinoff <jeff.koftinoff@statusbar.com>")
    print("// SPDX-License-Identifier: MIT")
    print("//")
    print("// GENERATED by crypto/python/crypto/gen_aes_gcm_kats.py - do not edit.")
    print(
        f"// Source: Project Wycheproof aes_gcm_test.json ({source['name']} {source['version']},"
    )
    print(
        f"// schema {data['schema']}, {data['numberOfTests']} tests), Apache-2.0; the AES-128 and"
    )
    print(
        "// AES-256 groups with a 96-bit IV and a 128-bit tag. Hex strings, as published."
    )
    print()
    print("#pragma once")
    print()
    print("#include <array>")
    print("#include <string_view>")
    print()
    print("// clang-format off")
    print("namespace statusbar::crypto::wycheproof {")
    print()
    print("struct AeadVector")
    print("{")
    print("    int tc_id;")
    print("    std::string_view comment;")
    print("    std::string_view flags;")
    print("    std::string_view key;")
    print("    std::string_view iv;")
    print("    std::string_view aad;")
    print("    std::string_view msg;")
    print("    std::string_view ct;")
    print("    std::string_view tag;")
    print("    bool valid;")
    print("};")
    print()
    emit_group("aes128_gcm", 128, data)
    emit_group("aes256_gcm", 256, data)
    print("}  // namespace statusbar::crypto::wycheproof")
    print("// clang-format on")
    return 0


if __name__ == "__main__":
    sys.exit(main())
