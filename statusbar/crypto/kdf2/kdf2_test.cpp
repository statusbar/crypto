#include "statusbar/test/test.hpp"

using namespace statusbar::crypto;
using statusbar::crypto::internal::span_compare;
using std::span;

TEST(kdf2, basic)
{
    // KDF2(Z, P, outLen):
    // Hash_1 = SHA-256(Z || 0x00000001 || P)
    // For outLen <= 32, output = Hash_1

    uint8_t Z[] = {0x01, 0x02, 0x03, 0x04};
    std::array<uint8_t, 32> output{};

    kdf2_sha256(Z, {}, output);

    // Output should be SHA-256(Z || 0x00000001)
    uint8_t expected_input[] = {0x01, 0x02, 0x03, 0x04, 0x00, 0x00, 0x00, 0x01};
    auto expected = sha256_sw(expected_input);

    EXPECT_TRUE(span_compare(output, expected));
}

TEST(kdf2, with_params)
{
    uint8_t Z[] = {0xAA, 0xBB};
    uint8_t P[] = {0xCC, 0xDD};
    std::array<uint8_t, 32> output{};

    kdf2_sha256(Z, P, output);

    // Output should be SHA-256(Z || 0x00000001 || P)
    uint8_t expected_input[] = {0xAA, 0xBB, 0x00, 0x00, 0x00, 0x01, 0xCC, 0xDD};
    auto expected = sha256_sw(expected_input);

    EXPECT_TRUE(span_compare(output, expected));
}

TEST(kdf2, multi_block)
{
    uint8_t Z[] = {0x42};
    std::array<uint8_t, 64> output{};

    kdf2_sha256(Z, {}, output);

    // First 32 bytes = SHA-256(Z || 0x00000001)
    uint8_t input1[] = {0x42, 0x00, 0x00, 0x00, 0x01};
    auto hash1 = sha256_sw(input1);

    // Second 32 bytes = SHA-256(Z || 0x00000002)
    uint8_t input2[] = {0x42, 0x00, 0x00, 0x00, 0x02};
    auto hash2 = sha256_sw(input2);

    EXPECT_TRUE(span_compare(span(output).subspan(0, 32), span(hash1)));
    EXPECT_TRUE(span_compare(span(output).subspan(32, 32), span(hash2)));
}

TEST(kdf2, partial_block)
{
    uint8_t Z[] = {0x42};
    std::array<uint8_t, 10> output{};

    kdf2_sha256(Z, {}, output);

    // First 10 bytes should be the first 10 bytes of SHA-256(Z || 0x00000001)
    uint8_t input1[] = {0x42, 0x00, 0x00, 0x00, 0x01};
    auto hash1 = sha256_sw(input1);

    EXPECT_TRUE(span_compare(span(output), span(hash1).subspan(0, 10)));
}

TEST(kdf2, input_too_large)
{
    // shared_secret + 4 + params > 256
    // Use shared_secret of 200 bytes and params of 100 bytes: 200 + 4 + 100 = 304 > 256
    std::array<uint8_t, 200> big_z{};
    big_z[0] = 0x42;
    std::array<uint8_t, 100> big_p{};
    big_p[0] = 0x43;
    std::array<uint8_t, 32> output{};
    bool ok = kdf2_sha256(big_z, big_p, output);
    EXPECT_TRUE(!ok);
}

