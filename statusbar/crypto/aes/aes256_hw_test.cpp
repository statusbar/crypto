// Cross-validate: _hw results must match software
//

TEST(aes256_hw, cross_validate)
{
    Aes256Key key = {{{0xde, 0xad, 0xbe, 0xef, 0x01, 0x23, 0x45, 0x67, 0x89, 0xab, 0xcd, 0xef, 0xfe, 0xdc, 0xba, 0x98,
                       0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff, 0x00}}};

    auto rk_sw = aes256_expand_key_sw(key);
    auto rk_hw = aes256_expand_key_hw(key);

    for (size_t i = 0; i <= aes256_num_rounds; ++i) {
        EXPECT_TRUE(span_compare(rk_sw.round_keys[i], rk_hw.round_keys[i]));
    }

    std::array<uint8_t, 16> block_sw = {
        0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f, 0x10};
    auto block_hw = block_sw;

    aes256_encrypt_block_sw(rk_sw, block_sw);
    aes256_encrypt_block_hw(rk_hw, block_hw);
    EXPECT_TRUE(span_compare(block_sw, block_hw));

    aes256_decrypt_block_sw(rk_sw, block_sw);
    aes256_decrypt_block_hw(rk_hw, block_hw);
    EXPECT_TRUE(span_compare(block_sw, block_hw));

    for (size_t len : {0, 1, 15, 16, 17, 31, 32, 48, 64, 100}) {
        std::vector<uint8_t> msg(len);
        for (size_t i = 0; i < len; ++i) {
            msg[i] = static_cast<uint8_t>(i * 37 + 13);
        }
        auto tag_sw = aes256_cmac_sw(rk_sw, msg);
        auto tag_hw = aes256_cmac_hw(rk_hw, msg);
        EXPECT_TRUE(span_compare(tag_sw, tag_hw));
    }
}

