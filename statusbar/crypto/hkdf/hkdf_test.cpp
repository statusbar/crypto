TEST(hkdf, expand_empty_output)
{
    auto prk = hkdf_sha256_extract({}, span<uint8_t const>{});
    std::array<uint8_t, 0> empty_okm{};
    // span over empty array has size 0
    bool ok = hkdf_sha256_expand(prk, {}, span<uint8_t>(empty_okm.data(), 0));
    EXPECT_TRUE(!ok);
}

TEST(hkdf, expand_info_too_large)
{
    auto prk = hkdf_sha256_extract({}, span<uint8_t const>{});
    std::array<uint8_t, 257> big_info{};
    std::array<uint8_t, 32> okm{};
    bool ok = hkdf_sha256_expand(prk, big_info, okm);
    EXPECT_TRUE(!ok);
}

TEST(hkdf, expand_too_large_output)
{
    auto prk = hkdf_sha256_extract({}, span<uint8_t const>{});
    // 8161 bytes exceeds the maximum of 255 * 32 = 8160
    std::vector<uint8_t> big_okm(8161);
    bool ok = hkdf_sha256_expand(prk, {}, span<uint8_t>(big_okm.data(), big_okm.size()));
    EXPECT_TRUE(!ok);
}

TEST(hkdf, expand_max_output)
{
    auto prk = hkdf_sha256_extract({}, span<uint8_t const>{});
    // Exactly 8160 bytes = 255 * 32 should succeed
    std::vector<uint8_t> max_okm(8160);
    bool ok = hkdf_sha256_expand(prk, {}, span<uint8_t>(max_okm.data(), max_okm.size()));
    EXPECT_TRUE(ok);
}

