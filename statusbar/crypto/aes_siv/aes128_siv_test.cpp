//
// RFC 5297 Appendix A.1 — Deterministic Authenticated Encryption
//

// Key:  fffefdfcfbfaf9f8f7f6f5f4f3f2f1f0 f0f1f2f3f4f5f6f7f8f9fafbfcfdfeff
// AD:   101112131415161718191a1b1c1d1e1f2021222324252627
// PT:   112233445566778899aabbccddee
// SIV:  85632d07c6e8f37f950acd320a2ecc93
// CT:   40c02b9690c4dc04daef7f6afe5c

TEST(aes128_siv, rfc5297_a1_encrypt)
{
    // clang-format off
    Aes128SivKey key = {{{
        0xff,0xfe,0xfd,0xfc,0xfb,0xfa,0xf9,0xf8,0xf7,0xf6,0xf5,0xf4,0xf3,0xf2,0xf1,0xf0,
        0xf0,0xf1,0xf2,0xf3,0xf4,0xf5,0xf6,0xf7,0xf8,0xf9,0xfa,0xfb,0xfc,0xfd,0xfe,0xff
    }}};
    std::array<uint8_t, 24> aad = {
        0x10,0x11,0x12,0x13,0x14,0x15,0x16,0x17,0x18,0x19,0x1a,0x1b,
        0x1c,0x1d,0x1e,0x1f,0x20,0x21,0x22,0x23,0x24,0x25,0x26,0x27
    };
    std::array<uint8_t, 14> pt = {
        0x11,0x22,0x33,0x44,0x55,0x66,0x77,0x88,0x99,0xaa,0xbb,0xcc,0xdd,0xee
    };
    std::array<uint8_t, 16> expected_siv = {
        0x85,0x63,0x2d,0x07,0xc6,0xe8,0xf3,0x7f,0x95,0x0a,0xcd,0x32,0x0a,0x2e,0xcc,0x93
    };
    std::array<uint8_t, 14> expected_ct = {
        0x40,0xc0,0x2b,0x96,0x90,0xc4,0xdc,0x04,0xda,0xef,0x7f,0x6a,0xfe,0x5c
    };
    // clang-format on

    auto buf = pt;
    auto siv = aes128_siv_encrypt(key, buf, aad);
    EXPECT_TRUE(span_compare(siv, expected_siv));
    EXPECT_TRUE(span_compare(buf, expected_ct));
}

