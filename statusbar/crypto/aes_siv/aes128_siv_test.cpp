TEST(aes128_siv, roundtrip)
{
    // clang-format off
    Aes128SivKey key = {{{
        0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08,0x09,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f,0x10,
        0x11,0x12,0x13,0x14,0x15,0x16,0x17,0x18,0x19,0x1a,0x1b,0x1c,0x1d,0x1e,0x1f,0x20
    }}};
    // clang-format on

    std::array<uint8_t, 4> aad_data = {0xaa, 0xbb, 0xcc, 0xdd};
    std::array<uint8_t, 20> original = {
        0x48, 0x65, 0x6c, 0x6c, 0x6f, 0x2c, 0x20, 0x57, 0x6f, 0x72, 0x6c, 0x64, 0x21, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    };

    auto buf = original;
    auto siv = aes128_siv_encrypt(key, buf, aad_data);
    EXPECT_TRUE(!span_compare(buf, original));

    bool ok = aes128_siv_decrypt(key, buf, siv, aad_data);
    EXPECT_TRUE(ok);
    EXPECT_TRUE(span_compare(buf, original));
}

