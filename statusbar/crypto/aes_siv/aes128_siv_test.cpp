TEST(aes128_siv, decrypt_bad_tag)
{
    // clang-format off
    Aes128SivKey key = {{{
        0xff,0xfe,0xfd,0xfc,0xfb,0xfa,0xf9,0xf8,0xf7,0xf6,0xf5,0xf4,0xf3,0xf2,0xf1,0xf0,
        0xf0,0xf1,0xf2,0xf3,0xf4,0xf5,0xf6,0xf7,0xf8,0xf9,0xfa,0xfb,0xfc,0xfd,0xfe,0xff
    }}};
    std::array<uint8_t, 24> aad = {
        0x10,0x11,0x12,0x13,0x14,0x15,0x16,0x17,0x18,0x19,0x1a,0x1b,
        0x1c,0x1d,0x1e,0x1f,0x20,0x21,0x22,0x23,0x24,0x25,0x26,0x27
    };
    std::array<uint8_t, 14> ct = {
        0x40,0xc0,0x2b,0x96,0x90,0xc4,0xdc,0x04,0xda,0xef,0x7f,0x6a,0xfe,0x5c
    };
    std::array<uint8_t, 16> bad_siv = {
        0x85,0x63,0x2d,0x07,0xc6,0xe8,0xf3,0x7f,0x95,0x0a,0xcd,0x32,0x0a,0x2e,0xcc,0x00
    };
    // clang-format on

    auto buf = ct;
    bool ok = aes128_siv_decrypt(key, buf, bad_siv, aad);
    EXPECT_TRUE(!ok);

    bool zeroed = true;
    for (auto b : buf) {
        if (b != 0) {
            zeroed = false;
        }
    }
    EXPECT_TRUE(zeroed);
}

