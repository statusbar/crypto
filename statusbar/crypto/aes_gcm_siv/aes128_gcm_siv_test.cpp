TEST(aes128_gcm_siv, decrypt_bad_tag)
{
    Aes128Key key = {{{0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00}}};
    std::array<uint8_t, 12> nonce = {0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00};
    std::array<uint8_t, 8> ct = {0xb5, 0xd8, 0x39, 0x33, 0x0a, 0xc7, 0xb7, 0x86};
    std::array<uint8_t, 16> bad_tag = {
        0x57,
        0x87,
        0x82,
        0xff,
        0xf6,
        0x01,
        0x3b,
        0x81,
        0x5b,
        0x28,
        0x7c,
        0x22,
        0x49,
        0x3a,
        0x36,
        0x00,  // last byte wrong
    };

    auto buf = ct;
    bool ok = aes128_gcm_siv_decrypt(key, nonce, buf, bad_tag, {});
    EXPECT_TRUE(!ok);

    // Buffer should be zeroed on failure
    bool zeroed = true;
    for (auto b : buf) {
        if (b != 0) {
            zeroed = false;
        }
    }
    EXPECT_TRUE(zeroed);
}

