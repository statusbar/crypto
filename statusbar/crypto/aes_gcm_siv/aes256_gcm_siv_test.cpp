TEST(aes256_gcm_siv, decrypt_bad_tag)
{
    Aes256Key key = {{{0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
                       0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00}}};
    std::array<uint8_t, 12> nonce = {0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00};
    std::array<uint8_t, 8> ct = {0xc2, 0xef, 0x32, 0x8e, 0x5c, 0x71, 0xc8, 0x3b};
    std::array<uint8_t, 16> bad_tag = {
        0x84,
        0x31,
        0x22,
        0x13,
        0x0f,
        0x73,
        0x64,
        0xb7,
        0x61,
        0xe0,
        0xb9,
        0x74,
        0x27,
        0xe3,
        0xdf,
        0x00,  // last byte wrong
    };

    auto buf = ct;
    bool ok = aes256_gcm_siv_decrypt(key, nonce, buf, bad_tag, {});
    EXPECT_TRUE(!ok);

    // Buffer should be zeroed on failure
    bool zeroed = true;
    for (auto b : buf) {
        if (b != 0) {
            zeroed = false;
        }
    }
    EXPECT_TRUE(zeroed);
}

