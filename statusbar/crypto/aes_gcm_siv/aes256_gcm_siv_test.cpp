TEST(aes256_gcm_siv, roundtrip)
{
    Aes256Key key = {{{0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
                       0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00}}};
    std::array<uint8_t, 12> nonce = {0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00};
    std::array<uint8_t, 4> aad = {0xaa, 0xbb, 0xcc, 0xdd};
    std::array<uint8_t, 20> original = {
        0x48, 0x65, 0x6c, 0x6c, 0x6f, 0x2c, 0x20, 0x57, 0x6f, 0x72, 0x6c, 0x64, 0x21, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    };

    auto buf = original;
    auto tag = aes256_gcm_siv_encrypt(key, nonce, buf, aad);
    EXPECT_TRUE(!span_compare(buf, original));

    bool ok = aes256_gcm_siv_decrypt(key, nonce, buf, tag, aad);
    EXPECT_TRUE(ok);
    EXPECT_TRUE(span_compare(buf, original));
}

